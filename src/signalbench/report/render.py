"""Evidence-only research and resume reporting."""

import json
from pathlib import Path

import pandas as pd

from signalbench.core import artifact

PENDING = "Not measured. No research conclusion or resume claim is available."


def run(cfg: dict) -> None:
    """Generate exact evidence tables; refuse reporting while anomaly review is pending."""
    out = Path(cfg["paths"]["results"])
    if (out / "REVIEW_REQUIRED.json").exists():
        raise RuntimeError(
            "Resolve REVIEW_REQUIRED.json through a documented audit before reporting"
        )
    sections = [
        "# Results for resume\n\nGenerated by `python -m signalbench.cli report`. "
        "Only measured outputs below may support resume claims.\n"
    ]
    benchmark = out / "benchmark.csv"
    if not benchmark.exists() and (out / "cpu/benchmark.csv").exists():
        benchmark = out / "cpu/benchmark.csv"
    complete = False
    if benchmark.exists():
        measured_models = set(pd.read_csv(benchmark).model)
        complete = {
            "tfidf",
            "finbert",
            "api_zero",
            "api_few",
            "api_rag",
            "qwen_base",
            "qlora",
        } <= measured_models
    backtest = out / "backtest.csv"
    if benchmark.exists():
        frame = pd.read_csv(benchmark)
        sections.append(
            f"## Classification\n\nSource: `{benchmark}`; "
            "script: `src/signalbench/eval/benchmark.py`.\n\n"
            + frame.to_markdown(index=False, floatfmt=".17g")
        )
        significance = benchmark.parent / "significance.json"
        if significance.exists():
            sections.append(
                "## Paired tests\n\nSource: `results/significance.json`.\n\n```json\n"
                + significance.read_text()
                + "\n```"
            )
    else:
        sections.append(
            "Classification F1, CIs, McNemar p-values, API cost and throughput: " + PENDING
        )
    if backtest.exists():
        frame = pd.read_csv(backtest)
        sections.append(
            "## Returns\n\nSource: `results/backtest.csv`; "
            "script: `src/signalbench/backtest/runner.py`.\n\n"
            + frame.to_markdown(index=False, floatfmt=".17g")
        )
        sections.append(
            "Main finding: exploratory estimates only; assess uncertainty, common model "
            "coverage and contamination before concluding predictive power. "
            "The maximum observed Sharpe is not an independently selected best strategy."
        )
    else:
        sections.append(
            "Filings, companies, period, IC, IC t-stat, hit rate, net Sharpe and drawdown: "
            + PENDING
        )
        sections.append("Main finding: the hypothesis has not yet been tested.")
    artifact("RESULTS_FOR_RESUME.md", cfg, "\n\n".join(sections) + "\n")
    status = {
        "benchmark_measured": benchmark.exists(),
        "benchmark_complete": complete,
        "backtest_measured": backtest.exists(),
        "training_measured": (out / "training/log.json").exists(),
    }
    artifact(out / "status.json", cfg, json.dumps(status, indent=2))
    report = "# Research results\n\n"
    report += benchmark.with_suffix(".md").read_text() if benchmark.exists() else PENDING
    report += "\n\n" + (backtest.with_suffix(".md").read_text() if backtest.exists() else PENDING)
    artifact(out / "README.md", cfg, report)
    root = Path("README.md")
    if root.exists():
        text = root.read_text()
        start, end = "<!-- GENERATED_RESULTS_START -->", "<!-- GENERATED_RESULTS_END -->"
        if start in text and end in text:
            generated = "\n\nFull comparison and trading hypothesis remain unmeasured.\n"
            if complete and backtest.exists():
                generated = (
                    "\n\nMeasured benchmark and backtest: [full evidence](results/README.md).\n"
                )
            if benchmark.exists():
                selected = pd.read_csv(benchmark)
                selected = selected[selected.partition.isin(["test", "ood"])]
                generated += (
                    "\nMeasured classification results "
                    "(preliminary unless all approaches are present):\n\n"
                )
                generated += selected[
                    ["model", "partition", "n", "macro_f1", "macro_f1_low", "macro_f1_high"]
                ].to_markdown(index=False, floatfmt=".17g")
                generated += f"\n\nSource: `{benchmark}`; generated by `make report`.\n\n"
            artifact(root, cfg, text.split(start)[0] + start + generated + end + text.split(end)[1])
